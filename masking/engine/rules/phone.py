"""กฎที่ 2 — เบอร์โทรศัพท์   [ผู้รับผิดชอบ: คนที่ 2 / Regex A]

โจทย์: ปิดบังตัวเลขเบอร์โทรศัพท์ด้วย X โดยเปิดเผยเฉพาะตัวเลข 4 หลักสุดท้าย
และต้องคงเครื่องหมายพิเศษ (+, -, เว้นวรรค) เอาไว้ตามเดิม

รูปแบบที่รองรับ:
    081-234-5678    -> XXX-XXX-5678      # มือถือ มีขีด
    0812345678      -> XXXXXX5678        # มือถือ ไม่มีขีด
    02-345-6789     -> XX-XXX-6789       # เบอร์บ้าน กทม.
    +66 81 234 5678 -> +XX XX XXX 5678   # รูปแบบสากล

หมายเหตุ:
  * การใช้ (?<![\w]) และ (?![\w]) เป็นกันชน เพื่อป้องกันการไปดึงเบอร์โทร
    ที่ติดกับตัวอักษร เช่น ID0812345678 ออกมาเซนเซอร์ผิดพลาด
"""
from __future__ import annotations

import re

from ..base import RegexRule

# กำหนดตัวอักษรที่ใช้ปิดบังข้อมูล (เหมือนที่ EmailRule ทำ)
MASK_CHAR = "X"


class PhoneRule(RegexRule):
    name = "phone"
    label = "เบอร์โทรศัพท์"
    description = "เบอร์โทรไทย (มือถือ/บ้าน/สากล) ปิดบังด้านหน้า เปิดเผย 4 ตัวท้าย"
    priority = 20

    pattern = re.compile(
        r"""
        (?<![\w])                            # [ปรับปรุง] กันชนหน้า: ต้องไม่ติดกับตัวอักษร/ตัวเลขอื่น
                                             # (แก้จาก (?<!\d) เพื่อไม่ให้จับเคสเช่น Tel0812345678)
        (?P<phone_number>                    # [ปรับปรุง] ใช้ Named group แบบ EmailRule
            (?:
                \+66[\s-]?\d{1,2}[\s-]?\d{3}[\s-]?\d{4}   # +66 81 234 5678
                |
                0\d{1,2}-\d{3}-\d{4}                      # [ปรับปรุง] รวบเคส 081- (มือถือ) และ 02- (บ้าน) ไว้ด้วยกัน
                |
                0\d{8,9}                                  # [ปรับปรุง] เบอร์โทรติดกัน (รองรับ 9 หลักเบอร์บ้าน และ 10 หลักเบอร์มือถือ)
            )
        )
        (?![\w])                             # [ปรับปรุง] กันชนหลัง: ต้องไม่ติดกับตัวอักษร/ตัวเลขอื่น
        """,
        re.VERBOSE,
    )

    def mask(self, match: re.Match[str]) -> str:
        text = match.group("phone_number")
        
        # นับจำนวนตัวเลขทั้งหมดในข้อความ
        digits_count = sum(c.isdigit() for c in text)
        
        # [ปรับปรุง] Edge Case ป้องกันข้อผิดพลาดกรณีตัวเลขมีน้อยกว่าหรือเท่ากับ 4 ตัว
        if digits_count <= 4:
            return text
            
        keep_from = digits_count - 4  # จุดที่เริ่มเก็บตัวเลขไว้ (4 ตัวท้าย)
        
        out = []
        seen = 0
        for c in text:
            if c.isdigit():
                out.append(c if seen >= keep_from else MASK_CHAR)
                seen += 1
            else:
                out.append(c)  # เก็บ -, +, เว้นวรรค ไว้ตามเดิม
                
        return "".join(out)


__all__ = ["PhoneRule"]
